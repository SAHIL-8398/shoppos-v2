export interface LocalizationContextType {
  language: Language;
  setLanguage: (lang: Language | string) => void;
  t: (key: string, ...args: (string | number)[]) => string;
}

const LocalizationContext = createContext<LocalizationContextType | undefined>(undefined);

export function LocalizationProvider({ children, activeLanguage = 'English' }: { children: ReactNode; activeLanguage?: string }) {
  const [currentLang, setCurrentLang] = React.useState<Language>(() => {
    if (activeLanguage === 'Hindi' || activeLanguage === 'Marathi' || activeLanguage === 'Tamil') {
      return activeLanguage as Language;
    }
    return 'English';
  });

  const setLanguage = (lang: Language | string) => {
    if (lang === 'hi' || lang === 'Hindi') setCurrentLang('Hindi');
    else if (lang === 'mr' || lang === 'Marathi') setCurrentLang('Marathi');
    else if (lang === 'ta' || lang === 'Tamil') setCurrentLang('Tamil');
    else setCurrentLang('English');
  };

  const t = (key: string, ...args: (string | number)[]): string => {
    const dictionary = languagePacks[currentLang] || languagePacks['English'];
    let translated = dictionary[key] || languagePacks['English'][key] || key;
    
    // Process variables like {0}, {1}
    args.forEach((val, idx) => {
      translated = translated.replace(`{${idx}}`, String(val));
    });

    return translated;
  };

  return (
    <LocalizationContext.Provider value={{ language: currentLang, setLanguage, t }}>
      {children}
    </LocalizationContext.Provider>
  );
}

export function useTranslation() {
  const context = useContext(LocalizationContext);
  if (!context) {
    throw new Error('useTranslation must be used within a LocalizationProvider');
  }
  return context;
}

export const useLocalization = useTranslation;
